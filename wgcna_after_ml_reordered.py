# How to read it: red dots (high feature value) clustering on the positive side
# means high expression pushes the prediction toward this class; blue dots
# (low value) clustering on the negative side means the opposite. If red and
# blue overlap near zero with no separation, the direction is inconsistent and
# the candidate is weaker even if its overall SHAP importance score is high.

# --- 2. Stability check (repeat the split several times, check whether the
#     same top-10 genes keep showing up) ---
# This repeats the single train-test split with different random seeds and
# tracks whether the same genes stay in the top 10 for the class of interest
# across all repeats. A gene that only appears in one split's top 10 may just
# be an artifact of that particular split rather than a robust signal.

N_REPEATS = 5
top_n_appearances = Counter()

for seed in range(N_REPEATS):
    X_tr, X_te, y_tr, y_te = train_test_split(
        X, y, test_size=0.2, random_state=seed, stratify=y
    )
    model_check = XGBClassifier(
        objective="multi:softprob",
        num_class=len(le.classes_),
        eval_metric="mlogloss",
        n_estimators=300,
        max_depth=4,
        learning_rate=0.05,
        random_state=seed,
        n_jobs=-1,
    )
    model_check.fit(X_tr, y_tr)

    explainer_check = shap.TreeExplainer(model_check)
    shap_values_check = explainer_check.shap_values(X_te)  # (n_samples, n_features, n_classes)

    imp_check = per_class_mean_abs_shap(shap_values_check, X_te.columns, le.classes_)
    top10_this_run = imp_check[CLASS_OF_INTEREST].sort_values(ascending=False).head(10).index.tolist()

    top_n_appearances.update(top10_this_run)

    # NOTE (bug fix): this print used to sit outside the for-loop, so only the
    # last seed's result was ever shown even though the counter above was
    # correctly accumulating all N_REPEATS runs. Moving it here prints every
    # seed's result as the loop runs.
    print(f"Seed {seed} - top 10 untuk {CLASS_OF_INTEREST}:", top10_this_run)

print(f"\n=== STABILITY CHECK: frekuensi muncul di top-10 dari {N_REPEATS} split (kelas: {CLASS_OF_INTEREST}) ===")
stability_table = pd.Series(top_n_appearances).sort_values(ascending=False)
print(stability_table)
stability_table.to_csv(f"/content/drive/My Drive/Latihan WGCNA/gambar alur 1/shap_stability_{CLASS_OF_INTEREST}.csv")
