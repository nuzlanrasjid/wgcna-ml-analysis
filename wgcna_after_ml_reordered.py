"""## Per-Class + Cross-Model SHAP Ranking (Biomarker Screening)"""

CLASS_OF_INTEREST = "Basal"  # change this to screen a different PAM50 subtype

def per_class_mean_abs_shap(shap_values, feature_names, class_names):
    """
    Accepts shap_values either as a 3D array (n_samples, n_features, n_classes)
    OR as a list per class (older shap versions), and returns a DataFrame
    (features x classes) of mean(|SHAP value|).
    """
    if isinstance(shap_values, list):
        arr = np.stack(shap_values, axis=-1)  # -> (n_samples, n_features, n_classes)
    else:
        arr = shap_values
    mean_abs = np.abs(arr).mean(axis=0)  # (n_features, n_classes)
    return pd.DataFrame(mean_abs, index=feature_names, columns=class_names)

imp_xgb = per_class_mean_abs_shap(shap_values_xgb, X_test.columns, le.classes_)
imp_rf = per_class_mean_abs_shap(shap_values_rf, X_test.columns, le.classes_)
imp_svm = per_class_mean_abs_shap(shap_values_svm, X_test_small.columns, le.classes_)

print(f"\n=== TOP 10 FITUR UNTUK KELAS: {CLASS_OF_INTEREST} (per model) ===")
print("\nXGBoost:")
print(imp_xgb[CLASS_OF_INTEREST].sort_values(ascending=False).head(10))
print("\nRandom Forest:")
print(imp_rf[CLASS_OF_INTEREST].sort_values(ascending=False).head(10))
print("\nSVM:")
print(imp_svm[CLASS_OF_INTEREST].sort_values(ascending=False).head(10))

# --- Cross-model rank agreement ---
# Rank is used instead of the raw SHAP value so XGBoost, Random Forest, and SVM
# can be compared fairly, since their SHAP values are not on the same numeric
# scale (TreeExplainer vs KernelExplainer). A feature with a low average rank
# (close to 1) is consistently important across all three models -- a more
# credible candidate than one with a single high score in only one model.
rank_table = pd.DataFrame({
    "xgb_rank": imp_xgb[CLASS_OF_INTEREST].rank(ascending=False),
    "rf_rank": imp_rf[CLASS_OF_INTEREST].rank(ascending=False),
    "svm_rank": imp_svm[CLASS_OF_INTEREST].rank(ascending=False),
})
rank_table["avg_rank"] = rank_table.mean(axis=1)
rank_table = rank_table.sort_values("avg_rank")

print(f"\n=== KANDIDAT BIOMARKER UNTUK KELAS: {CLASS_OF_INTEREST} (Konsisten di 3 Model) ===")
print(rank_table.head(10))

rank_table.to_csv(f"/content/drive/My Drive/Latihan WGCNA/gambar alur 1/shap_rank_agreement_{CLASS_OF_INTEREST}.csv")

